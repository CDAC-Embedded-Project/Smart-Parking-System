void LCD_UpdateParkingDisplay(void)
{
    char buf[17];

    LCD_SendCmd(0x01);      // Clear LCD
    HAL_Delay(2);

    LCD_SetCursor(0,0);
    sprintf(buf,"Total:%d", TOTAL_SLOTS);
    LCD_SendString(buf);

    LCD_SetCursor(1,0);

    if(parkedCount >= TOTAL_SLOTS)
    {
        LCD_SendString("Parking Full");
    }
    else
    {
        sprintf(buf,"Available:%d", TOTAL_SLOTS - parkedCount);
        LCD_SendString(buf);
    }
}
